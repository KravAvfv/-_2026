def _cell(c, text, size=11, bold=False, color=None):
    c.paragraphs[0].text = ""
    p = c.paragraphs[0]
    r = p.add_run(text)
    r.font.name, r.font.size, r.font.bold = FONT, Pt(size), bold
    if color:
        r.font.color.rgb = RGBColor.from_string(color)


def _bullets(c, items, size=11):
    c.paragraphs[0].text = ""
    for i, t in enumerate(items):
        p = c.paragraphs[0] if i == 0 else c.add_paragraph()
        p.paragraph_format.space_after = Pt(3)
        r = p.add_run("• " + t)
        r.font.name, r.font.size = FONT, Pt(size)


def _shade(cell, fill):
    tcPr = cell._tc.get_or_add_tcPr()
    sh = OxmlElement("w:shd")
    sh.set(qn("w:val"), "clear"); sh.set(qn("w:color"), "auto"); sh.set(qn("w:fill"), fill)
    tcPr.append(sh)


def build():
    doc = Document()
    sec = doc.sections[0]
    sec.page_width, sec.page_height = Cm(21), Cm(29.7)
    sec.left_margin = sec.right_margin = Cm(1.8)
    sec.top_margin = sec.bottom_margin = Cm(1.6)
    st = doc.styles["Normal"]
    st.font.name, st.font.size = FONT, Pt(12)
    st.element.rPr.rFonts.set(qn("w:eastAsia"), FONT)

    def para(text, size=12, bold=False, italic=False, align=None, after=6):
        p = doc.add_paragraph()
        p.paragraph_format.space_after = Pt(after)
        if align:
            p.alignment = align
        r = p.add_run(text)
        r.font.name, r.font.size, r.font.bold, r.font.italic = FONT, Pt(size), bold, italic
        return p

    para("Філософія: конспект для самопідготовки до семінарів 1–7", 16, True, align=WD_ALIGN_PARAGRAPH.CENTER)
    para("Навчальний матеріал для повторення (не читацький щоденник). Основа — «Конспект з філософії» "
         "(Мулико В. В.), звірений із першоджерелами; що виправлено — в кінці; позначка «доповнено» — тем, "
         "яких у конспекті немає. Колонка «Над чим подумати» — лише запитання: свою позицію сформулюйте самі.",
         11, italic=True, after=10)

    for num, theme, sources, rows in SEMINARS:
        para(f"{num}. {theme}", 14, True, after=2)
        para(f"Першоджерела: {sources}", 11, italic=True, after=4)
        t = doc.add_table(rows=1, cols=3)
        t.style = "Table Grid"
        t.alignment = WD_TABLE_ALIGNMENT.CENTER
        widths = (Cm(4.2), Cm(9.6), Cm(3.6))
        for c, w, h in zip(t.rows[0].cells, widths, ("Питання практичного завдання", "Тези, поняття, цитати",
                                                     "Над чим подумати")):
            c.width = w
            _shade(c, "DCE3EC")
            _cell(c, h, 11, True)
        for q, theses, think in rows:
            cells = t.add_row().cells
            for c, w in zip(cells, widths):
                c.width = w
            _cell(cells[0], q, 11, True)
            _bullets(cells[1], theses)
            _bullets(cells[2], think)
        para("", after=6)

    para("Що виправлено в конспекті", 14, True, after=4)
    t = doc.add_table(rows=1, cols=2)
    t.style = "Table Grid"
    for c, h in zip(t.rows[0].cells, ("У конспекті", "Як насправді")):
        _shade(c, "DCE3EC")
        _cell(c, h, 11, True)
    for a, b in CORRECTIONS:
        c0, c1 = t.add_row().cells
        _cell(c0, a, 11)
        _cell(c1, b, 11)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    doc.save(OUT)
    print(OUT)


if __name__ == "__main__":
    build()
