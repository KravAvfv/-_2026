def matrix(base):
    """Матриця критичності: значущість S × ймовірність O з кодами відмов."""
    rows = [("9–10", 9, 10), ("7–8", 7, 8), ("4–6", 4, 6), ("1–3", 1, 3)]
    cols = [("1–2", 1, 2), ("3–4", 3, 4), ("5–6", 5, 6), ("7–10", 7, 10)]
    f = Fig(1300, 1040, fpx=28)
    x0, y0, cw, rh = 230, 90, 260, 210
    f.text(x0 + 2 * cw, 30, "Ймовірність O", bold=True)
    f.text(110, y0 + 2 * rh, ["Значу-", "щість S"], bold=True)
    for j, (lab, *_r) in enumerate(cols):
        f.text(x0 + cw * j + cw / 2, 70, lab)
    for i, (lab, smin, smax) in enumerate(rows):
        f.text(x0 - 40, y0 + rh * i + rh / 2, lab)
        for j, (_, omin, omax) in enumerate(cols):
            score = (3 - i) + j
            fill = ["#FFFFFF", "#EDEDED", "#D6D6D6", "#BDBDBD", "#A6A6A6", "#8C8C8C", "#737373"][score]
            f.out.append(f'<rect x="{x0 + cw * j}" y="{y0 + rh * i}" width="{cw}" height="{rh}" fill="{fill}" '
                         'stroke="#000" stroke-width="2"/>')
            codes = [r[0] for r in M.FMECA if smin <= r[7] <= smax and omin <= r[8] <= omax]
            lines = [", ".join(codes[k:k + 2]) for k in range(0, len(codes), 2)]
            if lines:
                f.text(x0 + cw * j + cw / 2, y0 + rh * i + rh / 2, lines, bold=True)
    f.text(650, 1000, "Чим темніша клітинка, тим вища критичність C = S × O")
    return f.save(base)


def rpn_chart(base):
    """RPN до та після коригувальних дій (горизонтальні смуги)."""
    rows = sorted(M.FMECA, key=lambda r: -M.rpn(r))
    W, top, rh = 1300, 80, 66
    H = top + rh * len(rows) + 110
    f = Fig(W, H, fpx=28)
    x0, scale = 170, 2.4
    f.text(x0 + 500, 35, "RPN = S × O × D: до дій (темна смуга) і після (світла)", bold=True)
    for k, r in enumerate(rows):
        y = top + k * rh
        a, b = M.rpn(r), M.rpn_after(r)
        f.text(95, y + rh / 2, r[0])
        f.out.append(f'<rect x="{x0}" y="{y + 8}" width="{a * scale}" height="{rh / 2 - 6}" fill="#595959"/>')
        f.out.append(f'<rect x="{x0}" y="{y + rh / 2 + 2}" width="{b * scale}" height="{rh / 2 - 8}" '
                     'fill="#D0D0D0" stroke="#000" stroke-width="1"/>')
        f.text(x0 + a * scale + 50, y + rh / 4 + 4, str(a))
        f.text(x0 + b * scale + 50, y + 3 * rh / 4 - 2, str(b))
    for v in (100, 200):
        x = x0 + v * scale
        f.out.append(f'<line x1="{x}" y1="{top - 10}" x2="{x}" y2="{top + rh * len(rows)}" stroke="#000" '
                     'stroke-width="2" stroke-dasharray="8 6"/>')
        f.text(x, top + rh * len(rows) + 30, f"RPN = {v}")
    return f.save(base)
