"""Рис. «Модель системи інформаційної безпеки ТЦК та СП» (за структурою рис. 1.1 методичних рекомендацій)."""
from svg_fig import Fig


def draw(base):
    f = Fig(1280, 950, fpx=32)
    f.frame(150, 150, 960, 630, "Інформаційний простір ТЦК та СП", bottom=True)
    f.box(420, 60, 420, 96, ["Порушники: APT, інсайдер,", "хактивіст, постачальник"], shape="round")
    f.box(900, 60, 380, 96, ["Власник:", "начальник ТЦК та СП"], shape="round")
    f.box(420, 300, 330, 130, ["Атаки: фішинг, DDoS,", "підміна оновлень,", "фізичний доступ"])
    f.box(420, 520, 230, 100, ["Загрози", "К / Ц / Д"], shape="hex")
    f.box(900, 280, 380, 130, ["Контрзаходи:", "організаційні, правові,", "програмні, технічні"])
    f.box(900, 450, 260, 70, "Вразливості", shape="hex")
    f.box(900, 640, 200, 70, "Ризики", shape="hex")
    f.box(900, 880, 560, 96, ["Ресурси: Реєстр, дані ВЛК,", "розпорядження, засоби КЗІ, канали"],
          shape="round", bold=False)
    f.arrow([(420, 108), (420, 235)], "здійснюють", (420, 190))
    f.arrow([(900, 108), (900, 215)], "встановлює", (900, 180))
    f.arrow([(900, 345), (900, 415)], "зменшують", (900, 380))
    f.arrow([(420, 365), (420, 470)], "реалізують", (420, 418))
    f.arrow([(535, 520), (650, 520), (650, 450), (770, 450)], "використовують", (650, 485))
    f.arrow([(420, 570), (420, 640), (800, 640)], "створюють", (610, 640))
    f.arrow([(900, 485), (900, 605)], "збільшують", (900, 545))
    f.arrow([(1090, 60), (1215, 60), (1215, 880), (1180, 880)], "володіє", (1215, 470))
    f.arrow([(900, 675), (900, 832)], "загрожують", (900, 745))
    return f.save(base)


if __name__ == "__main__":
    import sys
    draw(sys.argv[1])
