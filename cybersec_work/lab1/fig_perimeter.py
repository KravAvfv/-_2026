"""Рис. «Архітектура периметра захисту та зони довіри ТЦК та СП» (Defense in Depth, сегментація)."""
from svg_fig import Fig


def draw(base):
    f = Fig(1700, 1010, fpx=32)
    # row 1 — зовнішні середовища
    f.frame(20, 20, 820, 190, "Зовнішнє середовище (недовірене)")
    f.box(230, 135, 330, 86, ["Громадяни", "(мережа Інтернет)"], shape="round")
    f.box(630, 135, 330, 86, ["Зовнішні адресати", "електронної пошти"], shape="round")
    f.frame(880, 20, 800, 190, "Відомча захищена мережа")
    f.box(1080, 135, 340, 86, ["Реєстр «Оберіг»", "(МО, Генштаб ЗСУ)"], shape="round")
    f.box(1480, 135, 340, 86, ["ДПСУ, обласний", "ТЦК та СП"], shape="round")
    # row 2 — периметр
    f.frame(20, 280, 1080, 230, "Зона 1: демілітаризована зона (ДМЗ)")
    f.box(230, 430, 330, 110, ["Анти-DDoS-", "фільтр, WAF"])
    f.box(580, 430, 300, 110, ["Сервіс", "електронної черги"])
    f.box(920, 430, 300, 110, ["Поштовий шлюз", "з «пісочницею»"])
    f.frame(1160, 280, 520, 230, "Зона 2: шлюз обміну")
    f.box(1420, 430, 440, 110, ["Криптошлюз КЗІ", "та міжмережевий екран"])
    # row 3 — внутрішні зони
    f.frame(20, 590, 1080, 400, "Зона 3: ЛОМ АС з КСЗІ (сегменти VLAN)", bottom=True)
    f.box(290, 670, 460, 110, ["АРМ ведення Реєстру", "(облік, оповіщення)"])
    f.box(810, 670, 460, 110, ["АРМ ВЛК", "(медичні дані)"])
    f.box(290, 835, 460, 110, ["Засоби біометрії", "та фотофіксації"])
    f.box(810, 835, 460, 110, ["Сервер документообігу", "та файлові ресурси"])
    f.frame(1160, 590, 520, 210, "Зона 4: керування безпекою")
    f.box(1420, 725, 460, 110, ["SIEM, EDR, NAC, PAM,", "резервні копії (офлайн)"])
    f.frame(1160, 830, 520, 160, "Зона 5: ізольована (РСО)", fill="#EDEDED")
    f.text(1420, 935, ["Автономні АРМ:", "мобілізаційні документи"])
    # flows
    f.arrow([(230, 178), (230, 373)], "HTTPS", (230, 245))
    f.arrow([(395, 430), (428, 430)])
    f.arrow([(630, 178), (630, 245), (920, 245), (920, 373)], "SMTP", (775, 245))
    f.arrow([(580, 485), (580, 588)], "через МЕ", (580, 550))
    f.arrow([(920, 485), (920, 588)], "перевірені", (920, 550))
    f.arrow([(1590, 212), (1590, 373)], "VPN, КЗІ", (1590, 245), both=True)
    f.arrow([(1420, 485), (1420, 550), (1130, 550), (1130, 640), (1102, 640)], both=True)
    f.arrow([(1102, 900), (1130, 900), (1130, 760), (1188, 760)], dash="8 6")
    return f.save(base, orientation="landscape")


if __name__ == "__main__":
    import sys
    draw(sys.argv[1])
