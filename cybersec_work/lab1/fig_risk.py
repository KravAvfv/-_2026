"""Рис. «Процес управління ризиками кібербезпеки ТЦК та СП» (шість складових процесного підходу)."""
from svg_fig import Fig

STEPS = [
    ("1. Опис бізнес-процесів", ["облік, оповіщення, ВЛК,", "соціальна підтримка"]),
    ("2. Збір ризиків", ["модель порушника,", "STRIDE, опитування"]),
    ("3. Оцінка ризиків", ["ймовірність × вплив,", "реєстр ризиків (1–25)"]),
    ("4. Планування заходів", ["п’ять видів заходів,", "Декларація (SoA)"]),
    ("5. Реалізація заходів", ["КСЗІ, сегментація,", "MFA, навчання"]),
    ("6. Оцінка ефективності", ["аудит, метрики SIEM,", "аналіз керівництвом"]),
]


def draw(base):
    f = Fig(1180, 915, fpx=34)
    pos = [(330, 110), (850, 110), (850, 420), (330, 420), (330, 730), (850, 730)]
    for (cx, cy), (t, ls) in zip(pos, STEPS):
        f.box(cx, cy, 440, 180, None)
        f.text(cx, cy - 50, t, bold=True)
        f.text(cx, cy + 25, ls)
    f.arrow([(550, 110), (628, 110)])
    f.arrow([(850, 200), (850, 328)])
    f.arrow([(630, 420), (552, 420)])
    f.arrow([(330, 510), (330, 638)])
    f.arrow([(550, 730), (628, 730)])
    f.arrow([(1070, 730), (1140, 730), (1140, 880), (60, 880), (60, 110), (108, 110)], "наступний цикл",
            (600, 880), dash="8 6")
    return f.save(base)


if __name__ == "__main__":
    import sys
    draw(sys.argv[1])
