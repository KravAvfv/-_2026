"""Рис. «Організаційна структура умовного ТЦК та СП з ролями СУІБ»."""
from svg_fig import Fig


def draw(base):
    f = Fig(1300, 930, fpx=32)
    f.box(650, 60, 520, 96, ["Начальник ТЦК та СП", "(власник ризиків СУІБ)"])
    f.box(330, 230, 440, 96, ["Заступник начальника", "(керівник СУІБ)"])
    f.box(970, 230, 500, 96, ["Служба захисту інформації", "та режимно-секретний орган"])
    f.arrow([(650, 108), (650, 150), (330, 150), (330, 182)])
    f.arrow([(650, 150), (970, 150), (970, 182)])
    f.frame(80, 360, 1140, 250, "Основні підрозділи", dash=None)
    for x, t in ((280, ["Відділення", "військового обліку", "(ведення Реєстру)"]),
                 (650, ["Відділення", "мобілізаційної роботи", "та комплектування"]),
                 (1020, ["Військово-лікарська", "комісія (ВЛК)"])):
        f.box(x, 515, 340, 130, t)
    f.frame(80, 650, 1140, 250, "Забезпечувальні підрозділи", dash=None)
    for x, t in ((225, ["Відділення", "соціальної", "підтримки"]), (505, ["Центр", "обслуговування", "громадян"]),
                 (790, ["Фінансово-", "господарське", "відділення"]), (1075, ["Група ІКТ", "та зв’язку"])):
        f.box(x, 805, 250, 130, t)
    f.arrow([(330, 278), (330, 358)], "управління", (330, 318))
    f.arrow([(110, 230), (45, 230), (45, 775), (78, 775)])
    f.arrow([(970, 278), (970, 358)], "контроль режиму і політик", (970, 318), dash="8 6")
    f.arrow([(1220, 230), (1265, 230), (1265, 775), (1222, 775)], dash="8 6")
    return f.save(base)


if __name__ == "__main__":
    import sys
    draw(sys.argv[1])
