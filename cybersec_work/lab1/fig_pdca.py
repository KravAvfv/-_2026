"""Рис. «Цикл PDCA СУІБ ТЦК та СП за розділами 4–10 ISO/IEC 27001:2022»."""
from svg_fig import Fig


def card(f, cx, cy, title, lines):
    f.box(cx, cy, 560, 180, None)
    f.text(cx, cy - 55, title, bold=True)
    f.text(cx, cy + 22, lines)


def draw(base):
    f = Fig(1200, 965, fpx=32)
    f.box(600, 60, 1100, 100, ["Вхід: вимоги зацікавлених сторін (закони, НД ТЗІ,",
                               "накази МО) та очікування щодо кібербезпеки"], shape="round")
    card(f, 300, 290, "ПЛАНУВАННЯ (Plan)", ["розд. 4–6: контекст, лідерство,", "оцінка ризиків, ДЗ (SoA)"])
    card(f, 900, 290, "ВИКОНАННЯ (Do)", ["розд. 7–8: ресурси, навчання,", "обробка ризиків, заходи A"])
    card(f, 900, 640, "ПЕРЕВІРКА (Check)", ["розд. 9: моніторинг, SIEM,", "внутрішній аудит, аналіз"])
    card(f, 300, 640, "ПОЛІПШЕННЯ (Act)", ["розд. 10: коригувальні дії,", "постійне поліпшення"])
    f.box(600, 465, 250, 96, ["СУІБ", "ТЦК та СП"], shape="hex", bold=True)
    f.box(600, 900, 1100, 100, ["Вихід: керована кібербезпека, захищені Реєстр,",
                                "дані ВЛК, безперервна мобілізаційна робота"], shape="round")
    f.arrow([(300, 110), (300, 198)])
    f.arrow([(580, 290), (618, 290)])
    f.arrow([(900, 380), (900, 548)])
    f.arrow([(620, 640), (582, 640)])
    f.arrow([(300, 550), (300, 382)])
    f.arrow([(900, 730), (900, 848)])
    return f.save(base)


if __name__ == "__main__":
    import sys
    draw(sys.argv[1])
