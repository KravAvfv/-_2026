"""Рисунки ЛР2: процес управління ризиками, етапи CRAMM, рівні управлінської роботи з ІБ у ТЦК та СП."""
from svg_fig import Fig


def rm_process(base):
    """Процес управління ризиками ІБ (ISO/IEC 27005, ISO 31000) з точками рішень."""
    f = Fig(1240, 1270, fpx=32)
    cx = 560
    f.box(cx, 60, 560, 84, "Встановлення контексту", bold=True)
    f.frame(200, 140, 720, 420, "Оцінювання ризиків", dash="10 6")
    f.box(cx, 250, 520, 76, "Ідентифікація ризиків")
    f.box(cx, 360, 520, 76, "Аналіз ризиків")
    f.box(cx, 470, 520, 76, "Оцінювання за критеріями")
    f.arrow([(cx, 102), (cx, 210)])
    f.arrow([(cx, 288), (cx, 320)])
    f.arrow([(cx, 398), (cx, 430)])
    f.box(cx, 650, 440, 110, ["Рішення 1: оцінка", "достатня?"], shape="hex")
    f.arrow([(cx, 508), (cx, 593)])
    f.box(cx, 820, 560, 84, "Обробка ризиків", bold=True)
    f.arrow([(cx, 705), (cx, 776)], "так", (cx + 40, 740))
    f.arrow([(340, 650), (150, 650), (150, 60), (278, 60)], "ні", (150, 360))
    f.box(cx, 990, 440, 110, ["Рішення 2: залишковий", "ризик прийнятний?"], shape="hex")
    f.arrow([(cx, 862), (cx, 933)])
    f.box(cx, 1170, 560, 84, "Прийняття ризиків", bold=True)
    f.arrow([(cx, 1045), (cx, 1126)], "так", (cx + 40, 1085))
    f.arrow([(340, 990), (150, 990), (150, 820), (278, 820)], "ні", (150, 905))
    # наскрізні процеси — вертикальні смуги з горизонтальним текстом (без поворотів)
    for x, words in ((1000, ["Комуні-", "кація", "і", "консуль-", "тування"]),
                     (1150, ["Моніто-", "ринг", "і", "перегляд"])):
        f.box(x, 615, 130, 1150, None)
        f.text(x, 615, words)
    return f.save(base)


def cramm(base):
    """Три етапи методики CRAMM з вхідними даними, шкалами та результатами."""
    f = Fig(1300, 1140, fpx=32)
    rows = [
        (170, "Етап 1. Ідентифікація та оцінка активів",
         ["дані: інтерв’ю з власниками, наслідки недоступності,", "знищення, розголошення, модифікації → 1–10;",
          "ПЗ і фізичні активи: вартість заміни → 1–10"]),
        (540, "Етап 2. Оцінка загроз, вразливостей і ризиків",
         ["рівень загрози: 5 градацій; рівень вразливості: 3 градації;",
          "матриця «цінність × загроза × вразливість»", "→ міра ризику 1–7"]),
        (910, "Етап 3. Вибір контрзаходів",
         ["бібліотека заходів за аспектами безпеки; рівень заходу", "відповідає мірі ризику; пріоритет — заходам",
          "проти кількох загроз і для систем високого ризику"]),
    ]
    for y, title, lines in rows:
        f.box(560, y, 1000, 270, None)
        f.text(560, y - 95, title, bold=True)
        f.text(560, y + 25, lines)
    f.box(1185, 355, 200, 150, ["Базового", "рівня", "досить?"], shape="round")
    f.arrow([(560, 305), (560, 405)], "детальний аналіз", (560, 355))
    f.arrow([(560, 675), (560, 775)], "звіт керівництву", (560, 725))
    f.arrow([(1060, 170), (1185, 170), (1185, 278)])
    f.arrow([(1060, 910), (1240, 910), (1240, 1100), (40, 1100), (40, 170), (58, 170)], "переоцінка після змін",
            (640, 1100), dash="8 6")
    return f.save(base)


def mgmt_levels(base):
    """Рівні управлінської роботи щодо забезпечення ІБ у ТЦК та СП."""
    f = Fig(1300, 1000, fpx=32)
    lv = [
        (110, "Стратегічний рівень — начальник ТЦК та СП",
         ["політика ІБ, прийнятний рівень ризику, ресурси"]),
        (330, "Тактичний рівень — керівник СУІБ, служба захисту інформації",
         ["методика CRAMM, класифікація, ролі, постачальники"]),
        (550, "Операційний рівень — адміністратор, аналітик, група ІКТ",
         ["доступ, моніторинг, резервування, інциденти, навчання"]),
        (770, "Контроль — внутрішній аудит і аналіз керівництвом",
         ["метрики, невідповідності, коригувальні дії"]),
    ]
    for y, t, l in lv:
        f.box(600, y, 1000, 150, None)
        f.text(600, y - 30, t, bold=True)
        f.text(600, y + 35, l)
    for a, b in ((185, 255), (405, 475), (625, 695)):
        f.arrow([(600, a), (600, b)])
    f.arrow([(1100, 770), (1220, 770), (1220, 110), (1102, 110)], "звіти", (1220, 440))
    f.text(600, 925, "Вниз — рішення і ресурси; вгору — звіти про стан ризиків")
    return f.save(base)
