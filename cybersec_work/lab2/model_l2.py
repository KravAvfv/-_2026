def risk_measure(v, t, u):
    """Апроксимація матриці CRAMM: цінність 1–10, загроза 1–5, вразливість 1–3 → міра ризику 1–7."""
    return 1 + round(2.5 * (v - 1) / 9 + 2 * (t - 1) / 4 + 1.5 * (u - 1) / 2)


