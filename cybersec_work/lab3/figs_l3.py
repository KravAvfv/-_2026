def allegro(base):
    """OCTAVE Allegro: чотири фази, вісім кроків."""
    f = Fig(1300, 1380, fpx=32)
    phases = [
        ("Фаза 1. Визначення рушійних чинників", [("1", "Критерії вимірювання ризику")]),
        ("Фаза 2. Профіль активів", [("2", "Профіль інформаційного активу"), ("3", "Контейнери активу")]),
        ("Фаза 3. Ідентифікація загроз", [("4", "Сфери занепокоєння"), ("5", "Сценарії загроз")]),
        ("Фаза 4. Ідентифікація та зменшення ризиків",
         [("6", "Ідентифікація ризиків"), ("7", "Аналіз ризиків"), ("8", "Підхід до зменшення")]),
    ]
    y = 30
    prev = None
    for title, steps in phases:
        h = 110 + 100 * len(steps)
        f.frame(40, y, 1220, h, title, dash="10 6")
        for k, (n, t) in enumerate(steps):
            cy = y + 110 + 100 * k
            f.box(800, cy, 720, 76, f"Крок {n}. {t}")
            if prev is not None:
                f.arrow([(800, prev + 38), (800, cy - 38)])
            prev = cy
        y += h + 30
    return f.save(base)


def frap(base):
    """Груповий процес FRAP: попередня зустріч, сесія, підсумковий етап."""
    f = Fig(1300, 1000, fpx=32)
    blocks = [
        (130, "Попередня зустріч (pre-FRAP)", ["межі аналізу, склад групи, визначення термінів,", "графік сесії"]),
        (410, "Сесія FRAP під керівництвом фасилітатора",
         ["мозковий штурм загроз → ймовірність і вплив (В / С / Н)", "→ пріоритет → наявні та пропоновані заходи"]),
        (690, "Підсумковий етап (post-FRAP)", ["звіт для власника, план заходів,", "рішення щодо залишкових ризиків"]),
    ]
    for y, t, l in blocks:
        f.box(650, y, 1100, 190, None)
        f.text(650, y - 50, t, bold=True)
        f.text(650, y + 35, l)
    f.arrow([(650, 225), (650, 315)])
    f.arrow([(650, 505), (650, 595)])
    f.text(650, 880, ["Учасники: власник активів, користувачі, фасилітатор, секретар;",
                      "результат — якісний, без точних числових оцінок"])
    return f.save(base)


