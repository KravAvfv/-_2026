def pl(n, one, few, many):
    """Узгодження іменника з числівником: 1 трек, 2 треки, 5 треків (11–14 — many)."""
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many


