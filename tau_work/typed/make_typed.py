def lach_asym4(w):
    w = np.asarray(w, float)
    L = 20 * np.log10(K) - 20 * np.log10(w)
    L -= np.where(w > 1 / T3, 40 * np.log10(w * T3), 0)
    L += np.where(w > 1 / T2, 20 * np.log10(w * T2), 0)
    L += np.where(w > 1 / T1, 20 * np.log10(w * T1), 0)
    return L


def phase_parts4(w):
    w = np.asarray(w, float)
    kol = -np.degrees(np.arctan2(2 * ZT * T3 * w, 1 - (T3 * w) ** 2))
    return -90 + 0 * w, kol, np.degrees(np.arctan(T2 * w)), np.degrees(np.arctan(T1 * w))


