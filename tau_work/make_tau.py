def plot(h, x, y, w, ht, f, ymax, yticks, name, asym=None):
    ox, oy = x + 55, y + ht - 45
    pw, ph = w - 90, ht - 90
    h.arrow((ox - 10, oy), (ox + pw + 25, oy))
    h.arrow((ox, oy + 10), (ox, oy - ph - 25))
    h.label("t, с", ox + pw - 5, oy - 14, 32)
    h.label(name, ox + 12, oy - ph - 8, 34)
    for tv in (5, 10, 15, 20):
        px = ox + pw * tv / 20
        h.line((px, oy - 6), (px, oy + 6), 3, over=False)
        h.label_c(str(tv), px, oy + 36, 30)
    for yv, s in yticks:
        py = oy - ph * yv / ymax
        h.line((ox - 6, py), (ox + 6, py), 3, over=False)
        h.label(s, ox - 52 if len(s) > 2 else ox - 34, py + 10, 30)
    if asym:
        a, b = asym  # штрихова асимптота y = a + b·t
        t = 0
        while t < 20:
            t1 = min(20, t + 0.9)
            ya, yb = a + b * t, a + b * t1
            if 0 <= ya <= ymax and 0 <= yb <= ymax:
                h.line((ox + pw * t / 20, oy - ph * ya / ymax), (ox + pw * t1 / 20, oy - ph * yb / ymax), 2, over=False)
            t += 1.6
    pts = [(ox + pw * t / 20, oy - ph * f(t) / ymax) for t in [i * 0.5 for i in range(41)]]
    h.stroke(pts, 4, amp=0.9, bow=0.2)
    for tv in (0, 5, 10, 15, 20):
        h.dot(ox + pw * tv / 20, oy - ph * f(tv) / ymax, 4)


