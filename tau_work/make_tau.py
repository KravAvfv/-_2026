def num(v, d=1):
    s = f"{v:.{d}f}".replace(".", ",").replace("-", "−")
    return "0" if s in ("−0", "−0,0", "0,0") and d <= 1 and abs(v) < 0.05 else s


def table(h, x, y, cw, rows, rh=CELL * 1.35, size=34, title=None):
    """Від руки накреслена таблиця: cw — ширини стовпців, rows — рядки (перший — шапка)."""
    if title:
        h.label(title, RIGHT - 190, y + 30, 38)
        y += CELL
    x0 = x + (RIGHT - x - sum(cw)) / 2
    tw = sum(cw)
    for i in range(len(rows) + 1):
        h.line((x0, y + 10 + i * rh), (x0 + tw, y + 10 + i * rh), 3)
    xx = x0
    for c in cw + [0]:
        h.line((xx, y + 10), (xx, y + 10 + len(rows) * rh), 3)
        xx += c
    for r, row in enumerate(rows):
        xx = x0
        for c, txt in zip(cw, row):
            h.label_c(txt, xx + c / 2, y + 10 + r * rh + rh * 0.68, size)
            xx += c


def dashed(h, a, b, step=16):
    (x1, y1), (x2, y2) = a, b
    L = math.hypot(x2 - x1, y2 - y1)
    n = max(1, int(L / step))
    for i in range(0, n, 2):
        t1, t2 = i / n, min(1, (i + 1) / n)
        h.line((x1 + (x2 - x1) * t1, y1 + (y2 - y1) * t1), (x1 + (x2 - x1) * t2, y1 + (y2 - y1) * t2), 2, over=False)


