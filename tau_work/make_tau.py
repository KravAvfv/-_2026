def det(h, x, base, cells, cw=115, rh=56, size=40):
    """Визначник від руки: значення в сітці і дві вертикальні риски."""
    n = len(cells)
    top = base - rh * 0.75
    h.line((x, top), (x + 4, top + n * rh), 4, over=False)
    for r, row in enumerate(cells):
        for c, v in enumerate(row):
            h.label_c(v, x + 30 + cw * c + cw / 2, base + r * rh, size)
    xr = x + 60 + cw * len(cells[0])
    h.line((xr, top), (xr - 3, top + n * rh), 4, over=False)
    return xr


def fig_hurwitz(h, x, y):
    h.label("Δ_3 =", x + 40, y + 120, 44)
    xr = det(h, x + 175, y + 70, [["a_2", "a_0", "0"], ["a_3", "a_1", "0"], ["0", "a_2", "a_0"]])
    h.label("=", xr + 20, y + 120, 44)
    det(h, xr + 60, y + 70, [["0,53", "11", "0"], ["0,01", "1,52", "0"], ["0", "0,53", "11"]], cw=120)


