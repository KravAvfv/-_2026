def spec(n, w):
    pages = sorted((ROOT / PHOTOS).glob(f"ПЗ{n}_стор*.jpg"), key=lambda p: int(p.stem.split("стор")[1]))
    blocks = [
        {"h1": "1. Мета та завдання роботи", "new_page": True},
        {"p": f"**Мета роботи:** {w['goal']}"},
        {"p": f"**Завдання:** {w['task']}"},
        {"p": "Вихідні дані індивідуального варіанту 8 наведено на рис. {fig:var}."},
        {"figure": {"id": "var", "src": w["var"], "caption": w["var_cap"], "width_cm": 16,
                    "orientation": "portrait"}},
        {"h1": "2. Хід виконання роботи", "new_page": True},
        {"p": "Розв'язання задачі виконано від руки в робочому зошиті. Фото аркушів наведено на "
              f"рис. {{fig:a1}}–{{fig:a{len(pages)}}}: теоретичні відомості, розв'язання для варіанту 8, "
              "перевірка результату та висновок."},
    ]
    for k, p in enumerate(pages, 1):
        blocks.append({"figure": {"id": f"a{k}", "src": str(p.relative_to(ROOT)), "width_cm": 12.5,
                                  "orientation": "portrait",
                                  "caption": f"Хід виконання практичної роботи №{n}, аркуш {k}"}})
    return {
        "lab_number": n,
        "work_label": "Практична робота №",
        "template": "ТАУ/Титульна сторінка для лб.docx",
        "subject": "Теорія автоматичного управління",
        "theme": w["theme"],
        "year": 2026,
        "toc": False,
        "output": f"ТАУ/ПЗ{n}_Кравченко_ІР-31_варіант8.docx",
        "blocks": blocks,
    }


if __name__ == "__main__":
    which = [int(a) for a in sys.argv[1:]] or list(WORKS)
    for n in which:
        y = HERE / f"report_pz{n}.yaml"
        y.write_text(yaml.safe_dump(spec(n, WORKS[n]), allow_unicode=True, sort_keys=False), encoding="utf-8")
        r = subprocess.run([sys.executable, str(ROOT / "tools/build_report.py"), str(y), "--pdf"],
                           cwd=ROOT, capture_output=True, text=True)
