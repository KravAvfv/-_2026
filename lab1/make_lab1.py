def goal_branch(branch):
    """TB tree: branch → level-2 goals (row) → each goal's measures stacked vertically in a frame."""
    code, text, subs = branch
    lines = ["flowchart TB", STYLE,
             "  classDef frame fill:#FFFFFF,stroke:#808080,stroke-width:1px;"]
    lines.append(f'  {nid(code)}["{q(wrap(code + ". " + text, 40))}"]:::l1')
    for c2, t2, leaves in subs:
        lines.append(f'  {nid(c2)}["{q(wrap(c2 + " " + t2, 21))}"]:::l2')
        lines.append(f"  {nid(code)} --> {nid(c2)}")
        sg = "F" + nid(c2)
        lines.append(f'  subgraph {sg}[" "]')
        lines.append("    direction TB")
        for c3, t3 in leaves:
            alt = c3[-1] in "аб"
            lines.append(f'    {nid(c3)}["{q(wrap(c3 + " " + t3, 21))}"]:::{"alt" if alt else "l3"}')
        for a, b in zip(leaves, leaves[1:]):
            lines.append(f"    {nid(a[0])} ~~~ {nid(b[0])}")
        lines.append("  end")
        lines.append(f"  class {sg} frame")
        lines.append(f"  {nid(c2)} --> {sg}")
    return "\n".join(lines) + "\n"


