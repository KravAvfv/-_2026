def wbs_groups(limit=9):
    """Consecutive subprojects grouped so that one figure holds at most `limit` work packages."""
    groups, cur = [], []
    for sp in WBS:
        if cur and sum(len(wps(x)) for x in cur) + len(wps(sp)) > limit:
            groups.append(cur); cur = []
        cur.append(sp)
    groups.append(cur)
    return groups


