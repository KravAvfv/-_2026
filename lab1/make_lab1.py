def write_diagrams():
    files = {
        "02_kp_workflow.mmd": KP_FLOW,
        "03_goal_tree_overview.mmd": goal_overview(),
        "09_wbs_overview.mmd": wbs_overview(),
    }
    for i, br in enumerate(GOALS):
        files[f"0{4 + i}_goal_tree_branch_{br[0]}.mmd"] = goal_branch(br)
    for old in DIAG.glob("1[0-9]_wbs_*"):
        old.unlink()
    for i, g in enumerate(wbs_groups()):
        files[f"{10 + i}_{group_file(g)}"] = wbs_detail(g)
    for name, body in files.items():
        p = DIAG / name
        if not p.exists() or p.read_text(encoding="utf-8") != body:
            p.write_text(body, encoding="utf-8")
    return files


