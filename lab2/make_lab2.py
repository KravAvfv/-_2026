# ---------------------------------------------------------------- analysis (computed from the model)
def analysis():
    detail = [D1, D2, D3, D4, D5, D6, D7]
    per_pool = {}
    handoffs = {}
    elem = {"task": 0, "user": 0, "service": 0, "send": 0, "manual": 0, "events": 0, "gw": 0, "data": 0}
    lane_roles = {}
    for spec in detail:
        st = stats(spec)
        for p in spec["pools"]:
            if p.get("collapsed"):
                continue
            base = p["id"].rstrip("b")
            key = base if base in POOLS else p["id"][:2]
            agg = per_pool.setdefault(key, {"lanes": set(), "tasks": 0, "events": 0, "gw": 0, "flows": 0,
                                            "handoffs": 0, "diagrams": 0})
            agg["diagrams"] += 1
            for l in p["lanes"]:
                agg["lanes"].add(l["role"]); lane_roles.setdefault(l["role"], set()).add(key)
            for n in p["nodes"]:
                if n["type"] == "task":
                    agg["tasks"] += 1; elem["task"] += 1
                    elem[n.get("kind", "none")] = elem.get(n.get("kind", "none"), 0) + 1
                elif n["type"] in ("start", "end", "intermediate", "throw"):
                    agg["events"] += 1; elem["events"] += 1
                else:
                    agg["gw"] += 1; elem["gw"] += 1
            elem["data"] += len(p.get("data", []))
            agg["flows"] += len(p["flows"])
            lane_of = {n["id"]: next(l["role"] for l in p["lanes"] if l["id"] == n["lane"]) for n in p["nodes"]}
            for f in p["flows"]:
                a, b = lane_of[f[0]], lane_of[f[1]]
                if a != b:
                    agg["handoffs"] += 1
                    handoffs[(a, b)] = handoffs.get((a, b), 0) + 1
    return per_pool, handoffs, elem, lane_roles


