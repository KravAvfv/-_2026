def report():
    B = []
    h1 = lambda t, new_page=False: B.append({"h1": t, **({"new_page": True} if new_page else {})})
    h2 = lambda t, new_page=False: B.append({"h2": t, **({"new_page": True} if new_page else {})})
    h3 = lambda t: B.append({"h3": t})
    p = lambda t: B.append({"p": t})
    bl = lambda items: B.append({"bullets": items})
    nl = lambda items: B.append({"numbered": items})
    tab = lambda **kw: B.append({"table": kw})
    fig = lambda src, cap, fid: B.append({"figure": {"id": fid, "src": f"{REL}/{src}", "caption": cap}})

    h1("Мета роботи")
    p("Вивчити мову об’єктно-орієнтованого моделювання UML (Unified Modeling Language) і створити UML-модель "
      "концепції автоматизованої системи — IoT-платформи «Щит-Лінк» для умовного РЦПДО «Щит-Північ», "
      "визначеного в лабораторній роботі № 1: діаграми варіантів використання, діяльності, послідовності "
      "та класів, а також проаналізувати призначення кожного виду діаграм.")

    h1("Короткі теоретичні відомості")
    p("UML — уніфікована мова візуального моделювання, яка є де-факто галузевим стандартом розроблення "
      "програмного забезпечення. Згідно з лекцією «Моделювання UML» вона слугує засобом комунікації в команді "
      "та із замовником, використовується для проєктування, реверс-інжинірингу і документування. Графічна "
      "нотація UML містить чотири типи елементів: фігури, значки, лінії та написи. Канонічні діаграми поділяють "
      "на структурні (класів, компонентів, розгортання), поведінкові (варіантів використання, діяльності, "
      "станів) і діаграми взаємодії (послідовності, кооперації).")
    p("Діаграма варіантів використання (прецедентів) відображає відношення між акторами та прецедентами "
      "системи. Актор — роль користувача або іншої системи (а не конкретна особа); основні актори ініціюють "
      "взаємодію, другорядні — обслуговують її. Прецедент (еліпс, назва — дієслово) описує суттєвий для актора "
      "результат роботи системи, не визначаючи способу реалізації. Між прецедентами встановлюють відношення "
      "включення «include» (базовий прецедент завжди використовує поведінку включеного) і розширення «extend» "
      "(спеціальний випадок базового), між акторами — узагальнення.")
    p("Діаграма діяльності — візуальне подання графу діяльностей, вершинами якого є дії, а переходи "
      "відбуваються після завершення дій; доріжки (swimlanes) показують виконавців, ромби — розгалуження, "
      "товсті лінії — паралельне виконання (fork/join). Діаграма послідовності відображає впорядковані в часі "
      "взаємодії об’єктів: лінії життя, повідомлення (суцільні — виклики, пунктирні — результати), фрагменти "
      "alt/loop; на ній використовують стереотипи межі (boundary), управління (control) і сутності (entity). "
      "Діаграма класів — статичне подання структури моделі: класи з атрибутами "
      "«<видимість><ім’я>: <тип>» та операціями, відношення асоціації (з кратністю), агрегації (незафарбований "
      "ромб), композиції (зафарбований ромб), узагальнення (трикутна стрілка) і залежності (пунктир).")

