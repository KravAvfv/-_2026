def tree():
    def node(b, kids=None):
        return {"id": b["id"], "name": b["name"], "children": kids or []}
    kids = []
    for b in A0_BOXES:
        sub = {"A1": A1_BOXES, "A2": A2_BOXES}.get(b["id"], [])
        kids.append(node(b, [node(x) for x in sub]))
    return {"kind": "tree", "title": f"Дерево вузлів моделі «{TITLE}»", "node": "A0", "number": "5",
            "root": {"id": "A0", "name": TITLE, "children": kids}}


D["05_node_tree"] = tree()


def feo(focus="A3"):
    arrows = []
    for a in A0_ARROWS:
        a2 = copy.deepcopy(a)
        if a["src"] == focus:
            arrows.append(a2)
            continue
        dst = [d for d in a["dst"] if d.startswith(focus + ":")]
        if dst:
            a2["dst"] = dst
            arrows.append(a2)
    return {"kind": "idef0", "node": "A0", "title": f"Взаємодія роботи «{A0_BOXES[2]['name']}»", "number": "6",
            "feo": True, "boxes": A0_BOXES, "arrows": arrows}


