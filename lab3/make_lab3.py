def scenario():
    keep_u = ["U1", "U3", "U4", "U5"]
    uows = [dict(u) for u in IDEF3_UOWS if u["id"] in keep_u]
    cols = {"U1": 0, "U3": 2, "U4": 2, "U5": 4}
    for u in uows:
        u["col"] = cols[u["id"]]
    js = [dict(j) for j in IDEF3_JUNCTIONS if j["id"] in ("J2", "J3")]
    js[0]["col"], js[1]["col"] = 1, 3
    refs = [dict(r) for r in IDEF3_REFS]
    refs[0]["col"], refs[1]["col"] = 0, 4
    links = [("U1", "J2"), ("J2", "U3"), ("J2", "U4"), ("U3", "J3"), ("U4", "J3"), ("J3", "U5"),
             ("R1", "U1", "referent"), ("R2", "U5", "referent")]
    return {"kind": "idef3", "node": "A3", "title": "Сценарій «Штатне виконання місії»", "number": "9",
            "uows": uows, "junctions": js, "referents": refs, "links": links}


D["10_scenario"] = scenario()


