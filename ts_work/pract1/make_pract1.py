def mmd_graph(V, E, short, G, groups, direction="TB", title=None, flip=(), width=14):
    keep = {v for _, nodes in groups for v in nodes}
    init = ["---", "config:", "  flowchart:", "    nodeSpacing: 16", "    padding: 6", "---"]
    out = init + HEAD + ([f"%% {title}"] if title else []) + [f"graph {direction}",
                                                        "  classDef cut stroke:#000,stroke-width:4px;"]
    for title, nodes in groups:
        if title is None:                      # вершини без рамки підсистеми
            for v in nodes:
                out.append(f'  {v}(["{V[v][0]}"])' if v in NAMES else f'  {v}["{ua(v)}<br/>{wrap(V[v][0], width)}"]')
            continue
        out.append(f'  subgraph {title[0]}["{title[1]}"]')
        for v in nodes:
            name = wrap(V[v][0], width)
            shape = ('(["', '"])') if V[v][1] == "зовнішній" else ('["', '"]')
            out.append(f"    {v}{shape[0]}{ua(v)}<br/>{name}{shape[1]}" if v not in NAMES
                       else f"    {v}{shape[0]}{name}{shape[1]}")
        out.append("  end")
    for (a, b, _, enc), lab in zip(E, short):
        if a in keep and b in keep:
            out.append(edge(b, a, lab, enc) if (a, b) in flip else edge(a, b, lab, enc))
    out.append(f"  class {','.join(v for v in G['cut'] if v in keep)} cut;")
    return "\n".join(out) + "\n"


