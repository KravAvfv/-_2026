def wrap(name, width=14):
    """Перенести довгу назву вершини на два рядки (за пробілом, найближчим до середини)."""
    if len(name) <= width or " " not in name:
        return name
    mid = len(name) / 2
    cut = min((i for i, ch in enumerate(name) if ch == " "), key=lambda i: abs(i - mid))
    return name[:cut] + "<br/>" + name[cut + 1:]


def edge(a, b, label, enc):
    if enc == "так":
        return f'  {a} == "{label}" === {b}'
    if enc == "частково":
        return f'  {a} -- "{label}" --- {b}'
    return f'  {a} -. "{label}" .- {b}'


