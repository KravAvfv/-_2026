def hit_time(M, target=2):
    idx = [i for i in range(len(M)) if i != target]
    Q = M[np.ix_(idx, idx)]
    t = np.linalg.solve(np.eye(len(idx)) - Q, np.ones(len(idx)))
    return dict(zip(idx, t))[0]


