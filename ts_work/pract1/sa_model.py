def graph_stats(V, E):
    """Метрики неорієнтованого графа: |V|, |E| (з кратними), щільність, степені, точки зчленування, мости."""
    adj = defaultdict(set)
    mult = defaultdict(int)
    for a, b, *_ in E:
        adj[a].add(b); adj[b].add(a)
        mult[frozenset((a, b))] += 1
    n, m = len(V), len(E)
    simple = len(mult)
    assert set(adj) == set(V), set(V) ^ set(adj)
    tin, low, cut, bridges, t = {}, {}, set(), [], [0]

    def dfs(v, parent):                      # алгоритм Тар'яна (DFS-часи входу й low-link)
        tin[v] = low[v] = t[0]; t[0] += 1
        children = 0
        for w in adj[v]:
            if w == parent:
                continue
            if w in tin:
                low[v] = min(low[v], tin[w])
            else:
                dfs(w, v); children += 1
                low[v] = min(low[v], low[w])
                if parent is not None and low[w] >= tin[v]:
                    cut.add(v)
                if low[w] > tin[v] and mult[frozenset((v, w))] == 1:
                    bridges.append((v, w))
        if parent is None and children > 1:
            cut.add(v)

    comps = 0
    for root in V:                            # граф може бути незв'язним — рахуємо компоненти
        if root not in tin:
            comps += 1
            dfs(root, None)
    deg = {v: len(adj[v]) for v in V}
    return dict(comps=comps, n=n, m=m, simple=simple, density=2 * simple / (n * (n - 1)), deg=deg,
                maxdeg=max(deg.values()), hub=max(deg, key=deg.get), cut=sorted(cut, key=lambda v: -deg[v]),
                bridges=bridges, enc=sum(1 for e in E if e[3] == "так") / m)


