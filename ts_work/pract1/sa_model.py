def kendall_w(S):
    """Коефіцієнт конкордації Кендалла (ранги по кожному експерту; більший бал — ранг 1; поправка на зв'язки)."""
    from scipy.stats import rankdata
    m, n = S.shape[1], S.shape[0]
    ranks = np.column_stack([rankdata(-S[:, j]) for j in range(m)])
    R = ranks.sum(axis=1)
    s = float(((R - R.mean()) ** 2).sum())
    ties = 0.0
    for j in range(m):
        _, cnt = np.unique(S[:, j], return_counts=True)
        ties += float((cnt ** 3 - cnt).sum())
    w = 12 * s / (m ** 2 * (n ** 3 - n) - m * ties)
    chi2 = m * (n - 1) * w
    return ranks, R, s, w, chi2


