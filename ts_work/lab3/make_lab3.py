def math_subs(v, key=None):
    if isinstance(v, str):
        import re
        parts = re.split(r"(\$[^$]*\$)", v)          # уже набрані формули не чіпаємо
        for j in range(0, len(parts), 2):
            for a, b in SUBS:
                parts[j] = parts[j].replace(a, b)
        return "".join(parts)
    if isinstance(v, list):
        return [math_subs(x) for x in v]
    if isinstance(v, dict):
        return {k: (x if k in ("code", "eq", "src") else math_subs(x, k)) for k, x in v.items()}
    return v


