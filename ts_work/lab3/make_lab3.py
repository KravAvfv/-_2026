def fig_effect(path):
    plt = plt_setup()
    fig, ax = plt.subplots(figsize=(6.4, 3.4), dpi=300)
    x = np.linspace(0, 150_000, 300)
    for i, ls in enumerate(("-", "--", ":")):
        ax.plot(x / 1000, O.R0[i] * np.exp(-O.K[i] * x), "k" + ls, lw=1.6, label=f"рівень {i + 1}: h = "
                f"{money(O.H[i] / 1000)} тис. грн")
        ax.plot(O.X_OPT[i] / 1000, O.LEVEL_RISK[i], "ko", ms=5)
    ax.set_xlabel(r"Вкладення $x_i$, тис. грн")
    ax.set_ylabel(r"Ризик рівня $R_i(x_i)$")
    ax.set_xlim(0, 150); ax.set_ylim(0, 0.42)
    ax.grid(True, color="#BBBBBB", lw=0.6)
    ax.legend(loc="upper right")
    fig.tight_layout(); fig.savefig(path, dpi=300); plt.close(fig)


def fig_alloc(path):
    plt = plt_setup()
    fig, ax = plt.subplots(figsize=(6.4, 3.2), dpi=300)
    names = ["рівномірний", "пропорційний\nвнеску", "оптимальний\n(SLSQP)"]
    allocs = [O.X_EQ, O.X_PROP, O.X_OPT]
    risks = [O.R_EQ, O.R_PROP, O.R_OPT]
    hatch = ["//", "..", ""]
    colors = ["white", "#BBBBBB", "#606060"]
    left = np.zeros(3)
    for i in range(3):
        vals = np.array([a[i] for a in allocs]) / 1000
        ax.barh(names, vals, left=left, color=colors[i], hatch=hatch[i], edgecolor="black", label=f"рівень {i + 1}")
        for y, (l, v) in enumerate(zip(left, vals)):
            ax.text(l + v / 2, y, f"{v:.1f}".replace(".", ","), ha="center", va="center", fontsize=11,
                    color="white" if i == 2 else "black")
        left += vals
    for y, r in enumerate(risks):
        ax.text(151, y, r"$R_{sys}$ = " + f(r, 4), va="center", fontsize=11)
    ax.set_xlim(0, 185)
    ax.set_xlabel("Розподіл бюджету 150 тис. грн, тис. грн")
    ax.legend(loc="upper center", bbox_to_anchor=(0.42, -0.25), ncol=3, frameon=False)
    fig.tight_layout(); fig.savefig(path, dpi=300); plt.close(fig)


