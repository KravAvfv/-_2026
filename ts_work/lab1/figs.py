def structfunc(base, subsystems, szib):
    f = TFig(1840, 1080, fpx=32, name="Структурно-функціональна схема")
    f.box(920, 70, 820, 90, ["Мікромережа багатоквартирного будинку"], bold=True)
    cw = 300
    xs = [20 + cw / 2 + i * (cw + 4) for i in range(len(subsystems))]
    f.line([(920, 115), (920, 165)], head=False)
    f.line([(xs[0], 165), (xs[-1], 165)], head=False)
    for x, (code, name, funcs) in zip(xs, subsystems):
        f.line([(x, 165), (x, 205)])
        f.box(x, 290, cw - 12, 170, [code] + wrap(name))
        ys = [470 + j * 108 for j in range(len(funcs))]
        f.line([(x, 375), (x, ys[0] - 44)], head=False)
        for j, (y, fn) in enumerate(zip(ys, funcs)):
            f.box(x, y, cw - 30, 88, wrap(fn, 16), shape="round")
            if j:
                f.line([(x, ys[j - 1] + 44), (x, y - 44)], head=False)
        f.line([(x, ys[-1] + 44), (x, 800)], head=False, dash="8 6")
    f.frame(20, 800, 1800, 260, "П7. Система забезпечення інформаційної безпеки (наскрізна підсистема)",
            fill="#EDEDED")
    sw = 1800 / len(szib)
    for i, fn in enumerate(szib):
        f.box(20 + sw / 2 + i * sw, 950, sw - 30, 100, fn.split(" ", 1) if len(fn) > 14 else [fn], shape="round")
    return f.save(base, orientation="landscape")
