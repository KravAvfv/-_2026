def math_subs(v):
    """Позначення з підкресленням у тексті → формули Word (крім лістингів)."""
    if isinstance(v, str):
        for a, b in SUBS:
            v = v.replace(a, b)
        return v
    if isinstance(v, list):
        return [math_subs(x) for x in v]
    if isinstance(v, dict):
        return {k: (x if k == "code" else math_subs(x)) for k, x in v.items()}
    return v


