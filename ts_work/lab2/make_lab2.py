def plt_setup():
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.family": "Times New Roman", "font.size": 12, "mathtext.fontset": "stix"})
    return plt


def fig_corr(path):
    plt = plt_setup()
    fig, axes = plt.subplots(1, 2, figsize=(6.4, 3.4), dpi=300)
    for ax, Mx, t in ((axes[0], M.CORR_BRIEF, "а) за методикою вказівок (n = 3)"),
                      (axes[1], M.CORR, "б) по 7 альтернативах (n = 7)")):
        ax.imshow(Mx, cmap="Greys", vmin=-1, vmax=1)
        for i in range(4):
            for j in range(4):
                v = Mx[i, j]
                ax.text(j, i, f(v), ha="center", va="center", fontsize=11,
                        color="white" if v > 0.45 else "black", fontweight="bold" if i != j and abs(v) >= 0.6 else None)
        ax.set_xticks(range(4), C); ax.set_yticks(range(4), C)
        ax.set_title(t, fontsize=12)
    fig.tight_layout()
    fig.savefig(path, dpi=300)
    plt.close(fig)


