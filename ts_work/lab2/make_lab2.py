def f(x, d=2):
    return f"{x:.{d}f}".replace(".", ",").replace("-", "−")


def pct(x, d=1):
    return f"{x * 100:.{d}f}".replace(".", ",") + " %"


# ------------------------------------------------------------------------------------------------ Mermaid
def wrap(text, n=17):
    out, cur = [], ""
    for w in text.split():
        if cur and len(cur) + len(w) + 1 > n:
            out.append(cur); cur = w
        else:
            cur = f"{cur} {w}".strip()
    return "<br/>".join(out + [cur])


def mmd_tree(stage, H, R, title, szib=False, levels=(1, 2, 3)):
    out = ["---", "config:", "  flowchart:", "    nodeSpacing: 14", "    rankSpacing: 36", "    padding: 6", "---",
           f"%% {title} (варіант 8, ЛР2 «Теорія систем»)",
           "%% Граф декомпозиції: система → рівні (вага W) → елементи (вага w, ризик r = p·c)",
           "graph LR",
           f'  S(["Система<br/>R<sub>sys</sub> = {f(R, 3)}"])']
    for i, h in enumerate(H, 1):
        if i not in levels:
            continue
        out.append(f'  L{i}["{LV[i - 1].split(". ")[0]}.<br/>{wrap(LV[i - 1].split(". ")[1], 15)}<br/>R<sub>sub</sub> = {f(h["R_sub"], 3)}"]')
        out.append(f'  S -- "W = {f(h["W"], 3)}" --> L{i}')
        for j, (n, w, p, c, r) in enumerate(h["elems"], 1):
            out.append(f'  L{i}E{j}["{wrap(n)}<br/>w = {f(w)}; r = {f(r, 3)}"]')
            out.append(f'  L{i} --> L{i}E{j}')
        if szib:
            out.append(f'  Z{i}(["СЗІБ:<br/>{SZIB[i - 1]}"])')
            out.append(f"  Z{i} -.-> L{i}")
            out.append(f"  style Z{i} stroke-dasharray:6 3")
    out.append("  style S stroke-width:3px")
    return "\n".join(out) + "\n"


