def scored(cat):
    """Return [(name, scores, total)] sorted as given, and the winner name."""
    w = [x[1] for x in cat["criteria"]]
    res = [(n, s, round(sum(a * b for a, b in zip(s, w)), 2)) for n, s in cat["candidates"]]
    best = max(res, key=lambda r: r[2])[0]
    return res, best


