def volume_text(v):
    """«4» → «4 записи», «≈ 600 / добу» → «≈ 600 записів / добу» (узгодження з числом)."""
    m = re.match(r"^(≈ )?([\d ]+?)(\s*/.*)?$", v)
    n = int(m.group(2).replace(" ", ""))
    return f"{m.group(1) or ''}{m.group(2)} {uk_form(n, 'запис', 'записи', 'записів')}{m.group(3) or ''}"

def diagrams():
    DIAG.mkdir(exist_ok=True)
    sql = G.sql()
    (HERE / "schema.sql").write_text(sql, encoding="utf-8")
    (DIAG / "01_context.mmd").write_text(G.context_mmd(), encoding="utf-8")
    for g in M.GROUPS:
        (DIAG / f"0{1 + g}_logical_g{g}.puml").write_text(G.er(g, True, DIRS[g]), encoding="utf-8")
        (DIAG / f"0{5 + g}_physical_g{g}.puml").write_text(G.er(g, False, DIRS[g]), encoding="utf-8")
    for f in sorted(DIAG.glob("*.puml")) + sorted(DIAG.glob("*.mmd")):
        tool = "puml_render.py" if f.suffix == ".puml" else "mmd_render.py"
        r = subprocess.run([sys.executable, str(ROOT / "tools" / tool), str(f)], capture_output=True, text=True)
        lay = json.loads((f.with_suffix(".layout.json")).read_text(encoding="utf-8"))
        print(f"{f.stem}: {lay['orientation']} {lay[lay['orientation']]['font_pt']} pt legible={lay['legible']}")
        if r.returncode or not lay["legible"]:
            sys.exit(f"{f.name}: rendering/legibility failed\n{r.stderr}")
    # фрагмент DDL: тип mission_state і таблиця mission
    st = {s.strip().split("(")[0].strip(): s.strip() + ";" for s in sql.split(";\n") if s.strip().startswith("CREATE")}
    frag = "\n\n".join([st["CREATE TYPE mission_state AS ENUM"], st["CREATE TABLE mission"]])
    lay = ddl_gen.code_figure(frag, DIAG / "10_ddl_mission.png", width_cm=14.5)
    print(f"10_ddl_mission: {lay['portrait']['font_pt']} pt legible={lay['legible']}")
    # перевірка в тимчасовому кластері PostgreSQL
    res = G.verify(sql, [(q, False) for q in SEED] + [(q, e) for _, q, e in TESTS])
    seed_ok = all(ok for _, ok, _ in res["tests"][:len(SEED)])
    test_res = res["tests"][len(SEED):]
    if not seed_ok or not all(ok for _, ok, _ in test_res):
        sys.exit(f"DB verification failed: {res}")
    print(f"PostgreSQL {res['version']}: {res['tables']} tables, {res['fks']} FK, {res['checks']} CHECK, "
          f"{len(TESTS)} tests OK")
    (HERE / "verify.json").write_text(json.dumps(res, ensure_ascii=False, indent=1), encoding="utf-8")
    return res


