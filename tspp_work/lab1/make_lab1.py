def n_cols():
    return sum(len(t["cols"]) for t in M.T)


def rel_rows():
    rows = []
    for t in M.T:
        for c, p in G.fks(t):
            par = "1" if G.is_nn(t, c) else "0..1"
            ch = "0..1" if "U" in G.flags(c) else "0..∗"
            rows.append([M.TABLES[p]["ua"], t["ua"], f"{par} : {ch}", c[0], M.REL[(t["name"], c[0])]])
    return rows


