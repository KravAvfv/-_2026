"""Узгодження числівника з іменником в українській мові (називний / знахідний відмінок).

    n_uk(22, "подія", "події", "подій")  -> "22 події"
    n_uk(5, "функція", "функції", "функцій") -> "5 функцій"
    n_uk(21, "запис", "записи", "записів") -> "21 запис"
Форма one — для 1, 21, 31…; few — для 2–4, 22–24…; many — для 0, 5–20, 25–30…
"""


def uk_form(n, one, few, many):
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return one
    if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        return few
    return many


def n_uk(n, one, few, many):
    return f"{n} {uk_form(n, one, few, many)}"
