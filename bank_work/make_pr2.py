NAVY, RED, GREY = RGBColor(0x1F, 0x38, 0x64), RGBColor(0xC0, 0x00, 0x00), RGBColor(0x59, 0x59, 0x59)


def _box(sl, x, y, w, h, text, fill=RGBColor(0xE8, 0xEE, 0xF7), size=12, bold=False, dash=False):
    s = sl.shapes.add_shape(MSO_SHAPE.ROUNDED_RECTANGLE, Cm(x), Cm(y), Cm(w), Cm(h))
    s.fill.solid(); s.fill.fore_color.rgb = fill
    s.line.color.rgb = NAVY; s.line.width = Pt(1.5)
    if dash:
        s.line.dash_style = 4
    tf = s.text_frame; tf.word_wrap = True
    for m in ("margin_left", "margin_right", "margin_top", "margin_bottom"):
        setattr(tf, m, Cm(0.1))
    tf.text = text
    for p in tf.paragraphs:
        p.alignment = PP_ALIGN.CENTER
        for r in p.runs:
            r.font.size = Pt(size); r.font.bold = bold; r.font.color.rgb = RGBColor(0, 0, 0)
    return s


def _arrow(sl, x1, y1, x2, y2, color=NAVY, dash=False, width=2):
    c = sl.shapes.add_connector(MSO_CONNECTOR.STRAIGHT, Cm(x1), Cm(y1), Cm(x2), Cm(y2))
    c.line.color.rgb = color; c.line.width = Pt(width)
    if dash:
        c.line.dash_style = 4
    ln = c.line._get_or_add_ln()
    tail = ln.makeelement(qn("a:tailEnd"), {"type": "triangle", "w": "med", "len": "med"})
    ln.append(tail)
    return c


def _label(sl, x, y, w, text, size=10, color=GREY, bold=False, h=0.9):
    t = sl.shapes.add_textbox(Cm(x), Cm(y), Cm(w), Cm(h))
    tf = t.text_frame; tf.word_wrap = True
    tf.margin_left = tf.margin_right = Cm(0.05)
    tf.text = text
    for p in tf.paragraphs:
        p.alignment = PP_ALIGN.CENTER
        for r in p.runs:
            r.font.size = Pt(size); r.font.color.rgb = color; r.font.bold = bold
    return t


def _boundary(sl, x, y1, y2, name):
    _arrow(sl, x, y1, x, y2, RED, dash=True, width=2.25)
    ln = sl.shapes[-1].line._get_or_add_ln()
    for el in ln.findall(qn("a:tailEnd")):
        ln.remove(el)
    _label(sl, x - 0.8, y1 - 0.75, 1.6, name, 13, RED, True)


