def build():
    wb = variant_book(1)
    sheet(wb, "Профіль")["B4"] = STUDENT
    put_rows(sheet(wb, "Активи"), 5, ASSETS, "BCDEF")
    put_rows(sheet(wb, "Чернетка"), 15, DRAFT_LOG, "ABC")
    ws = sheet(wb, "Ризики")
    for i, r in enumerate(RISKS):
        row = 5 + i
        for col, v in zip("BCDEFG", r[:6]):
            ws[f"{col}{row}"] = v
        ws[f"J{row}"] = r[6] or None
        ws[f"K{row}"] = r[7]
        ws[f"L{row}"] = r[8]
        ws[f"S{row}"] = r[9]
    put_rows(sheet(wb, "Обґрунтування"), 5, JUSTIFY, "ABCD")
    sheet(wb, "Обґрунтування")["A13"] = INJECT
    out = out_path(1)
    wb.save(out)
    return out


def verify(path):
    res = evaluate(path)
    ok = True
    names = {r[0] for r in RISKS}
    asset_names = {a[0] for a in ASSETS}
    assert names <= asset_names, names - asset_names
    print("ризиків:", len(RISKS), " активів:", len(ASSETS))
    rows = []
    for i, r in enumerate(RISKS):
        n = 5 + i
        lvl, zone, chk, q = (val(res, "Ризики", f"{c}{n}") for c in "HIRQ")
        rows.append((i + 1, r[4], r[5], lvl, zone, r[6], chk, q))
        print(f"  №{i + 1:2d} P{r[4]} C{r[5]} = {lvl} {zone:<9} топ:{r[6] or '-':<3} {r[7]:<10} перевірка={chk!s:<4} "
              f"залишок={q}")
        if r[6] == "Так" and chk != "ОК":
            ok = False
    # топ-5 = п'ять найвищих (за рівних — більші C)
    order = sorted(range(len(RISKS)), key=lambda k: (-RISKS[k][4] * RISKS[k][5], -RISKS[k][5]))
    top = {k for k in range(len(RISKS)) if RISKS[k][6] == "Так"}
    if set(order[:5]) != top:
        print("ПОМИЛКА: топ-5 не збігається з п'ятьма найвищими:", [k + 1 for k in order[:6]])
        ok = False
    lvl5, lvl6 = order[4], order[5]
    if (RISKS[lvl5][4] * RISKS[lvl5][5], RISKS[lvl5][5]) == (RISKS[lvl6][4] * RISKS[lvl6][5], RISKS[lvl6][5]):
        print("ПОМИЛКА: нечітка межа топ-5")
        ok = False
    for c in ("B5", "B6", "B7", "B8", "B9", "B10", "B11", "B12", "B13"):
        print("  Бюджет", c, val(res, "Бюджет", c))
    if val(res, "Бюджет", "B12") not in (0, 0.0) or val(res, "Бюджет", "B11") != 5:
        ok = False
    if val(res, "Бюджет", "B7") != "У межах бюджету":
        ok = False
    print("PASS" if ok else "FAIL")
    return ok


