def l2_cli(macs=None):
    macs = macs or {}
    sw = ["enable", "configure terminal", f"hostname {L2_SW}", "no ip domain-lookup", f"banner motd #{BANNER}#",
          f"vlan {QVLAN}", " name QUARANTINE", " exit"]
    for desc, rng, *_ in FREE:
        sw += [f"interface {rng}", f" description {desc}", " switchport mode access",
               f" switchport access vlan {QVLAN}", " shutdown", " exit"]
    sw += ["end", "show interfaces status", "copy running-config startup-config"]
    ps = ["configure terminal"]
    for port, devs, desc, mx, how, mode in WORK:
        ps += [f"interface fastEthernet {port}", f" description {desc}", " switchport mode access",
               " switchport port-security", f" switchport port-security maximum {mx}"]
        if how == "sticky":
            ps.append(" switchport port-security mac-address sticky")
        else:
            ps += [f" switchport port-security mac-address {macs.get(d, f'<MAC {d}>')}" for d in devs]
        ps += [f" switchport port-security violation {mode}", " exit"]
    ps += ["end"]
    chk = ["show port-security", "show port-security address", "copy running-config startup-config"]
    rec = ["configure terminal", "interface fastEthernet 0/1", " shutdown", " no shutdown", " end",
           "show interfaces status", "show port-security interface fastEthernet 0/1"]
    return {"1_вільні_порти_карантин": sw, "2_port_security": ps, "3_перевірка_port_security": chk,
            "4_відновлення_Fa0_1": rec}


